// Builds index.html (the HyperFrames composition) and captions from script.json and the voice-over lengths.
// Run: node build.mjs   (after node voice.mjs). No dependencies beyond Node 22.
import { readFileSync, writeFileSync } from 'node:fs';

const beats = JSON.parse(readFileSync('script.json', 'utf8'));
const durs = JSON.parse(readFileSync('assets/vo/durations.json', 'utf8'));

// Scene plan. pre/post/gap are seconds of breathing room around the voice. A fixed scene (screen
// recording) has its own length, and its beats start at the given seconds into the recording.
const plan = [
  { id: 'problem', pre: 0.5, gap: 0.4, post: 0.5 },
  { id: 'title', pre: 0.4, post: 0.8 },
  { id: 'journey', fixed: 35.5, at: { b04: 0.3, b05: 5.4, b06: 10.9, b07: 18.1, b08: 27.7 } },
  { id: 'agent', pre: 0.5, post: 0.9 },
  { id: 'market', pre: 0.4, post: 1.0 },
  { id: 'fees', pre: 0.5, post: 1.0 },
  { id: 'poolsrec', pre: 0.4, post: 1.6 },
  { id: 'pools', pre: 0.3, post: 1.0 },
  { id: 'built', pre: 0.4, post: 0.6 },
  { id: 'personas', pre: 0.2, post: 0.5 },
  { id: 'arch', pre: 0.3, post: 0.5 },
  { id: 'truth', pre: 0.3, post: 0.8 },
  { id: 'pillars', pre: 0.4, post: 0.8 },
  { id: 'end', pre: 0.4, post: 2.2 },
];

const r3 = (x) => Math.round(x * 1000) / 1000;
const T = { s: {}, vo: {}, c: {} };
let t = 0;
for (const sc of plan) {
  const mine = beats.filter((b) => b.scene === sc.id);
  const start = t;
  if (sc.fixed) {
    for (const b of mine) T.vo[b.id] = { start: r3(start + sc.at[b.id]), dur: durs[b.id] };
    t += sc.fixed;
  } else {
    t += sc.pre;
    mine.forEach((b, i) => {
      if (i > 0) t += sc.gap ?? 0.5;
      T.vo[b.id] = { start: r3(t), dur: durs[b.id] };
      t += durs[b.id];
    });
    t += sc.post;
  }
  T.s[sc.id] = { start: r3(start), dur: r3(t - start) };
}
const total = r3(t);

// Scene markup: data-scene (+ data-at / data-len) becomes data-start / data-duration.
let scenes = readFileSync('src/scenes.html', 'utf8');
let z = 1;
scenes = scenes.replace(
  /<(section|video|div)([^>]*?)data-scene="([a-z]+)"([^>]*)>/g,
  (m, tag, a, id, b) => {
    const s = T.s[id];
    if (!s) throw new Error('unknown scene ' + id);
    const attrs = a + b;
    const atM = attrs.match(/data-at="([\d.]+)"/);
    const lenM = attrs.match(/data-len="([\d.]+)"/);
    const start = r3(s.start + (atM ? +atM[1] : 0));
    const dur = r3(lenM ? +lenM[1] : s.dur - (atM ? +atM[1] : 0));
    const idM = attrs.match(/id="([^"]+)"/);
    if (atM && idM) T.c[idM[1]] = { start, dur };
    const clean = attrs.replace(/\s*data-(at|len)="[\d.]+"/g, '');
    return `<${tag}${clean} data-start="${start}" data-duration="${dur}" data-track-index="${z++}">`;
  },
);

const audio = Object.entries(T.vo)
  .map(
    ([id, v]) =>
      `    <audio id="vo-${id}" class="clip" src="assets/vo/${id}.m4a" data-start="${v.start}" data-duration="${r3(v.dur)}" data-track-index="${100 + Object.keys(T.vo).indexOf(id)}" data-volume="1"></audio>`,
  )
  .join('\n');

const css = readFileSync('src/cards.css', 'utf8') + readFileSync('src/video.css', 'utf8');
const anim = readFileSync('src/anim.js', 'utf8');
const html = `<!doctype html>
<!-- Generated by build.mjs from src/ and script.json. Edit those, then run: node build.mjs -->
<html lang="en">
<head>
<meta charset="utf-8">
<title>UnitMarket demo video</title>
<style>
${css}
</style>
<script src="vendor/gsap.min.js"></script>
</head>
<body>
  <div id="root" data-composition-id="main" data-start="0" data-duration="${total}" data-width="1920" data-height="1080">
${scenes}
${audio}
  </div>
<script>
const T = ${JSON.stringify(T)};
${anim}
</script>
</body>
</html>
`;
writeFileSync('index.html', html);

// Captions: split each beat at sentence and clause ends, time each piece by its share of characters.
const ts = (x) => {
  const ms = Math.round(x * 1000);
  const p = (n, w = 2) => String(n).padStart(w, '0');
  return `${p(Math.floor(ms / 3600000))}:${p(Math.floor(ms / 60000) % 60)}:${p(Math.floor(ms / 1000) % 60)},${p(ms % 1000, 3)}`;
};
const cues = [];
for (const b of beats) {
  const v = T.vo[b.id];
  const parts = b.text
    .match(/[^.:?!]+[.:?!]?/g)
    .map((s) => s.trim())
    .filter(Boolean);
  const chunks = [];
  for (const p of parts) {
    if (chunks.length && (chunks[chunks.length - 1] + ' ' + p).length <= 60)
      chunks[chunks.length - 1] += ' ' + p;
    else chunks.push(p);
  }
  const n = chunks.reduce((a, c) => a + c.length, 0);
  let c0 = v.start;
  for (const c of chunks) {
    const d = (v.dur * c.length) / n;
    cues.push([c0, c0 + d, c]);
    c0 += d;
  }
}
writeFileSync(
  'captions.srt',
  cues.map(([a, b, c], i) => `${i + 1}\n${ts(a)} --> ${ts(b)}\n${c}\n`).join('\n'),
);
writeFileSync(
  'captions.vtt',
  'WEBVTT\n\n' +
    cues
      .map(([a, b, c]) => `${ts(a).replace(',', '.')} --> ${ts(b).replace(',', '.')}\n${c}\n`)
      .join('\n'),
);
console.log(
  JSON.stringify(
    {
      total,
      scenes: Object.fromEntries(Object.entries(T.s).map(([k, v]) => [k, `${v.start}+${v.dur}`])),
    },
    null,
    1,
  ),
);
