// Provenance check (architecture 2.4 item 2, lane 17): every file that carries a copy header
// ("Origin: <repo>@<sha>:<path>" or "Adapted from <repo>/<path> at <sha>" in a comment within the
// first 30 lines) must be listed in docs/PROVENANCE.md, the header must name a commit sha, and
// the list must not name a file that no longer exists.
//
//   node scripts/check-provenance.mjs [--root <dir>] [--write]
//
// The generated list sits between <!-- provenance:begin --> and <!-- provenance:end -->. Files
// that cannot hold comments (JSON) are listed by hand in the table above it; those table rows are
// checked for existence only. --write rewrites the generated list from the headers found.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { listFiles, read, report, resolveRoot } from './lib/walk.mjs';

const NAME = 'check-provenance';
const ROOT = resolveRoot(process.argv, import.meta.url);
const DOC = join(ROOT, 'docs', 'PROVENANCE.md');
const BEGIN = '<!-- provenance:begin -->';
const END = '<!-- provenance:end -->';
// Built from parts so this file does not contain the repository name it forbids elsewhere.
const SIM_REPO = 'AIC_Hackathon_' + 'UnitMarket';
const CODE = /\.(ts|tsx|mts|cts|js|mjs|cjs|sql)$/;
const COMMENT = /^\s*(\/\/|\/\*|\*|--|#)/;
const HAS_SHA = /(?:@|\bat\s+)[0-9a-f]{7,40}\b/;

const violations = [];
const add = (file, line, message) =>
  violations.push({ file, line, message: `provenance: ${message}` });

const headered = [];
for (const file of listFiles(ROOT)) {
  if (!CODE.test(file.rel) || file.rel.startsWith('docs/design/')) continue;
  const lines = read(file).split('\n').slice(0, 30);
  const idx = lines.findIndex(
    (l) => COMMENT.test(l) && l.includes(SIM_REPO) && /(?:\bOrigin:|\bAdapted from\b)/.test(l),
  );
  if (idx < 0) continue;
  headered.push(file.rel);
  // The sha may wrap onto the next two comment lines.
  const window = lines
    .slice(idx, idx + 3)
    .filter((l, k) => k === 0 || COMMENT.test(l))
    .join(' ')
    .replace(/(^|\s)(?:\/\/|\/\*|\*|--|#)\s*/g, ' ');
  if (!HAS_SHA.test(window))
    add(file.rel, idx + 1, 'header names no commit sha (use @<sha> or "at <sha>")');
}

const docText = existsSync(DOC) ? readFileSync(DOC, 'utf8') : '';
const section = (() => {
  const a = docText.indexOf(BEGIN);
  const b = docText.indexOf(END);
  return a >= 0 && b > a ? docText.slice(a + BEGIN.length, b) : '';
})();
const listed = [...section.matchAll(/`([^`]+)`/g)].map((m) => m[1]);

if (process.argv.includes('--write')) {
  const block = `${BEGIN}\n\n${[...headered]
    .sort()
    .map((f) => `- \`${f}\``)
    .join('\n')}\n\n${END}\n`;
  let next;
  if (docText.includes(BEGIN) && docText.includes(END)) {
    next =
      docText.slice(0, docText.indexOf(BEGIN)) +
      block +
      docText.slice(docText.indexOf(END) + END.length).replace(/^\n/, '');
  } else {
    next = `${docText.trimEnd()}\n\n## Files with a copy header\n\nGenerated by \`node scripts/check-provenance.mjs --write\`. Do not edit between the markers.\n\n${block}`;
  }
  writeFileSync(DOC, next);
  console.log(`${NAME}: wrote ${headered.length} file(s) to docs/PROVENANCE.md`);
  process.exit(0);
}

for (const f of headered)
  if (!listed.includes(f))
    add(f, 1, `has a copy header but is not listed in docs/PROVENANCE.md (run --write)`);
for (const f of listed)
  if (!existsSync(join(ROOT, f))) add('docs/PROVENANCE.md', 1, `lists ${f}, which is missing`);
// Hand-written table rows: first cell is a path.
for (const m of docText.matchAll(/^\|\s*([^|\s][^|]*?)\s*\|/gm)) {
  const cell = m[1].replace(/`/g, '');
  if (/^(File|-+)$/.test(cell) || /\s/.test(cell)) continue;
  if (!existsSync(join(ROOT, cell)))
    add('docs/PROVENANCE.md', 1, `table lists ${cell}, which is missing`);
}
process.exit(report(NAME, violations));
